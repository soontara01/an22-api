--   btree_gist: extension "trusted" — เจ้าของ database (an22_owner) สร้างได้โดยไม่ต้องเป็น superuser;
--   Azure Flexible Server: ต้องเปิด BTREE_GIST ใน server parameter azure.extensions ก่อน migrate (db/README.md)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ราคาขาย (SkuPrice, D2: ราคาเดียวทั้งบริษัท) — ช่วงของ SKU เดียวกันห้ามทับ (ตาข่ายชั้นสุดท้าย; แอปตรวจก่อนด้วย findOverlap() เพื่อข้อความไทย)
CREATE TABLE dt_sku_prices (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  product_id      bigint NOT NULL,
  price           numeric(14, 2) NOT NULL CHECK (price >= 0),
  start_date      date NOT NULL,
  end_date        date CHECK (end_date >= start_date),
  note            text NOT NULL DEFAULT '',
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_sku_prices_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_sku_prices_product_fkey FOREIGN KEY (tenant_id, product_id)
    REFERENCES dt_products (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_sku_prices_no_overlap EXCLUDE USING gist (
    tenant_id WITH =, product_id WITH =, daterange(start_date, end_date, '[]') WITH &&)
);
CREATE INDEX dt_sku_prices_product_idx ON dt_sku_prices (tenant_id, product_id);

-- โปรโมชั่น (Promotion) — scope / ของแถม / สาขา เก็บเป็น array / jsonb ตามรูปของ TS ไม่มี FK:
-- โปรที่หมดอายุแล้วเป็นประวัติ (ลบ SKU / หมวดที่โปรหมดอายุอ้างได้ — mock เช็กเฉพาะโปรที่ยังไม่หมดอายุ)
CREATE TABLE dt_promotions (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  code               text NOT NULL CHECK (code ~ '^[A-Z0-9-]{1,30}$'),
  name               text NOT NULL CHECK (btrim(name) <> ''),
  note               text NOT NULL DEFAULT '',
  type               text NOT NULL CHECK (type IN ('item_discount', 'bill_discount', 'free_goods')),
  start_date         date NOT NULL,
  end_date           date CHECK (end_date >= start_date),
  enabled            boolean NOT NULL DEFAULT true,
  priority           integer NOT NULL DEFAULT 0 CHECK (priority BETWEEN 0 AND 999),
  stackable          boolean NOT NULL DEFAULT false,
  scope_all          boolean NOT NULL DEFAULT false,
  scope_product_ids  bigint[] NOT NULL DEFAULT '{}',
  scope_category_ids bigint[] NOT NULL DEFAULT '{}',
  min_qty            integer NOT NULL DEFAULT 1 CHECK (min_qty >= 0),
  min_amount         numeric(14, 2) NOT NULL DEFAULT 0 CHECK (min_amount >= 0),
  -- PromotionDiscount { kind, value, maxDiscount } / PromotionFreeGoods { items: [{ productId, qty }], repeat, maxSets }
  discount           jsonb,
  free_goods         jsonb,
  -- [] = ทุกสาขา (D2)
  branch_ids         bigint[] NOT NULL DEFAULT '{}',
  created_at         timestamptz NOT NULL,
  created_by         bigint,
  created_by_kind    text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at         timestamptz NOT NULL,
  updated_by         bigint,
  updated_by_kind    text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_promotions_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_promotions_tenant_code_key UNIQUE (tenant_id, code),
  CONSTRAINT dt_promotions_kind_check CHECK ((type = 'free_goods') = (free_goods IS NOT NULL) AND (discount IS NULL OR free_goods IS NULL))
);

CREATE TRIGGER set_row_stamp BEFORE INSERT OR UPDATE ON dt_sku_prices FOR EACH ROW EXECUTE FUNCTION set_row_stamp();
CREATE TRIGGER set_row_stamp BEFORE INSERT OR UPDATE ON dt_promotions FOR EACH ROW EXECUTE FUNCTION set_row_stamp();

ALTER TABLE dt_sku_prices ENABLE ROW LEVEL SECURITY;
ALTER TABLE dt_sku_prices FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON dt_sku_prices
  USING (tenant_id = app_tenant_id()) WITH CHECK (tenant_id = app_tenant_id());

ALTER TABLE dt_promotions ENABLE ROW LEVEL SECURITY;
ALTER TABLE dt_promotions FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON dt_promotions
  USING (tenant_id = app_tenant_id()) WITH CHECK (tenant_id = app_tenant_id());

GRANT SELECT, INSERT, UPDATE, DELETE ON dt_sku_prices, dt_promotions TO an22_app, an22_platform;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO an22_app, an22_platform;
