-- V9 (ขั้น 10): ใบลดหนี้ (CreditNote) + ใบเปลี่ยนสินค้า (Exchange) — เอกสาร append-only ทั้งใบ (ออกแล้วไม่แก้ / ไม่ลบ)
--   ผู้ซื้อของใบลดหนี้ = snapshot ของใบกำกับตอนออก เข้ารหัสแบบเดียวกับใบกำกับ (AAD dt_credit_notes.buyer:<tenant>)
--   product_id / method_id / promotion_id ไม่มี FK (ประวัติ, ชื่อเป็น snapshot); บรรทัดอ้างบรรทัดบิลด้วย sale_line_index
CREATE TABLE dt_credit_notes (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  cn_no           text NOT NULL,
  sale_id         bigint NOT NULL,
  order_no        text NOT NULL,
  tax_invoice_no  text,
  buyer_enc       bytea,
  sale_date       timestamptz NOT NULL,
  date            timestamptz NOT NULL DEFAULT now(),
  cashier         text NOT NULL,
  reason          text NOT NULL CHECK (btrim(reason) <> ''),
  subtotal        numeric(14, 2) NOT NULL,
  deduction       numeric(14, 2) NOT NULL,
  total           numeric(14, 2) NOT NULL CHECK (total >= 0),
  vat             numeric(14, 2) NOT NULL,
  shift_id        bigint,
  branch_id       bigint NOT NULL,
  terminal_id     integer,
  pos_id          text NOT NULL DEFAULT '',
  vat_registered  boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_credit_notes_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_credit_notes_tenant_no_key UNIQUE (tenant_id, cn_no),
  CONSTRAINT dt_credit_notes_sale_fkey FOREIGN KEY (tenant_id, sale_id) REFERENCES dt_sales (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_credit_notes_shift_fkey FOREIGN KEY (tenant_id, shift_id) REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_credit_notes_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_credit_notes_terminal_fkey FOREIGN KEY (tenant_id, terminal_id)
    REFERENCES dt_pos_terminals (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_credit_notes_sale_idx ON dt_credit_notes (tenant_id, sale_id);
CREATE INDEX dt_credit_notes_shift_idx ON dt_credit_notes (tenant_id, shift_id);
CREATE INDEX dt_credit_notes_branch_idx ON dt_credit_notes (tenant_id, branch_id, date);
CREATE INDEX dt_credit_notes_terminal_idx ON dt_credit_notes (tenant_id, terminal_id);

CREATE TABLE dt_credit_note_lines (
  tenant_id       bigint NOT NULL,
  credit_note_id  bigint NOT NULL,
  position        integer NOT NULL CHECK (position >= 0),
  sale_line_index integer NOT NULL CHECK (sale_line_index >= 0),
  product_id      bigint NOT NULL,
  sku             text NOT NULL,
  name            text NOT NULL,
  short_name      text NOT NULL,
  unit            text NOT NULL,
  factor          integer NOT NULL,
  qty             integer NOT NULL CHECK (qty > 0),
  amount          numeric(14, 2) NOT NULL,
  vat_type        text NOT NULL CHECK (vat_type IN ('vat7', 'exempt')),
  vat             numeric(14, 2) NOT NULL,
  cogs            numeric(14, 2) NOT NULL,
  serial          text,
  free            boolean NOT NULL,
  restock         boolean NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, credit_note_id, position),
  CONSTRAINT dt_credit_note_lines_note_fkey FOREIGN KEY (tenant_id, credit_note_id)
    REFERENCES dt_credit_notes (tenant_id, id) ON DELETE RESTRICT
);

-- ของแถมที่ลูกค้าเก็บไว้เกินสิทธิ์ (หักจากยอดคืน)
CREATE TABLE dt_credit_note_deductions (
  tenant_id       bigint NOT NULL,
  credit_note_id  bigint NOT NULL,
  position        integer NOT NULL CHECK (position >= 0),
  promotion_id    bigint NOT NULL,
  product_id      bigint NOT NULL,
  sku             text NOT NULL,
  name            text NOT NULL,
  qty             integer NOT NULL CHECK (qty > 0),
  unit_price      numeric(14, 2) NOT NULL,
  amount          numeric(14, 2) NOT NULL,
  vat_type        text NOT NULL CHECK (vat_type IN ('vat7', 'exempt')),
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, credit_note_id, position),
  CONSTRAINT dt_credit_note_deductions_note_fkey FOREIGN KEY (tenant_id, credit_note_id)
    REFERENCES dt_credit_notes (tenant_id, id) ON DELETE RESTRICT
);

-- การคืนเงิน (SalePayment) — reference เลขบัตรเต็ม → 400 ก่อนถึงนี่ (PCI DSS)
CREATE TABLE dt_credit_note_refunds (
  tenant_id          bigint NOT NULL,
  credit_note_id     bigint NOT NULL,
  position           integer NOT NULL CHECK (position >= 0),
  method_id          bigint NOT NULL,
  name               text NOT NULL,
  type               text NOT NULL,
  amount             numeric(14, 2) NOT NULL,
  tendered           numeric(14, 2) NOT NULL,
  reference          text NOT NULL DEFAULT '',
  installment_months integer,
  created_at         timestamptz NOT NULL,
  created_by         bigint,
  created_by_kind    text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, credit_note_id, position),
  CONSTRAINT dt_credit_note_refunds_note_fkey FOREIGN KEY (tenant_id, credit_note_id)
    REFERENCES dt_credit_notes (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_credit_note_refunds_method_idx ON dt_credit_note_refunds (tenant_id, method_id);

CREATE TABLE dt_exchanges (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  ex_no           text NOT NULL,
