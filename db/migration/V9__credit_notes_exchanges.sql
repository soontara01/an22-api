  order_no        text NOT NULL,
  sale_date       timestamptz NOT NULL,
  date            timestamptz NOT NULL DEFAULT now(),
  cashier         text NOT NULL,
  reason          text NOT NULL CHECK (btrim(reason) <> ''),
  shift_id        bigint,
  branch_id       bigint NOT NULL,
  terminal_id     integer,
  pos_id          text NOT NULL DEFAULT '',
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_exchanges_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_exchanges_tenant_no_key UNIQUE (tenant_id, ex_no),
  CONSTRAINT dt_exchanges_sale_fkey FOREIGN KEY (tenant_id, sale_id) REFERENCES dt_sales (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_exchanges_shift_fkey FOREIGN KEY (tenant_id, shift_id) REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_exchanges_branch_fkey FOREIGN KEY (tenant_id, branch_id) REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_exchanges_terminal_fkey FOREIGN KEY (tenant_id, terminal_id)
    REFERENCES dt_pos_terminals (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_exchanges_sale_idx ON dt_exchanges (tenant_id, sale_id);
CREATE INDEX dt_exchanges_shift_idx ON dt_exchanges (tenant_id, shift_id);
CREATE INDEX dt_exchanges_branch_idx ON dt_exchanges (tenant_id, branch_id);
CREATE INDEX dt_exchanges_terminal_idx ON dt_exchanges (tenant_id, terminal_id);

CREATE TABLE dt_exchange_lines (
  tenant_id       bigint NOT NULL,
  exchange_id     bigint NOT NULL,
  position        integer NOT NULL CHECK (position >= 0),
  sale_line_index integer NOT NULL CHECK (sale_line_index >= 0),
  product_id      bigint NOT NULL,
  sku             text NOT NULL,
  name            text NOT NULL,
  short_name      text NOT NULL,
  unit            text NOT NULL,
  factor          integer NOT NULL,
  qty             integer NOT NULL CHECK (qty > 0),
  old_serial      text,
  new_serial      text,
  restock         boolean NOT NULL,
  cost_in         numeric(14, 2) NOT NULL,
  cost_out        numeric(14, 2) NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, exchange_id, position),
  CONSTRAINT dt_exchange_lines_exchange_fkey FOREIGN KEY (tenant_id, exchange_id)
    REFERENCES dt_exchanges (tenant_id, id) ON DELETE RESTRICT
