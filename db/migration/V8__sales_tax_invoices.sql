-- V8 (ขั้น 9): บิลขาย (Sale) + บรรทัด + การชำระ + ใบกำกับภาษีเต็มรูป (TaxInvoice)
--   ไม่เก็บ returnStatus / creditedTotal / creditNoteNos / exchangeNos (คำนวณจากใบลดหนี้ / ใบเปลี่ยนตอนอ่าน — ขั้น 10)
--   บรรทัด / การชำระ = append-only (บิลไม่เปลี่ยน — void เปลี่ยนแค่สถานะของบิล); product_id / method_id ไม่มี FK (ประวัติ, ชื่อเป็น snapshot)
CREATE TABLE dt_sales (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id              bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  order_no               text NOT NULL,
  sold_at                timestamptz NOT NULL DEFAULT now(),
  cashier                text NOT NULL DEFAULT '',
  customer               text NOT NULL DEFAULT '',
  subtotal               numeric(14, 2) NOT NULL,
  item_discount          numeric(14, 2) NOT NULL DEFAULT 0,
  bill_discount          numeric(14, 2) NOT NULL DEFAULT 0,
  manual_discount        numeric(14, 2) NOT NULL DEFAULT 0,
  total                  numeric(14, 2) NOT NULL,
  vat                    numeric(14, 2) NOT NULL DEFAULT 0,
  rounding               numeric(14, 2) NOT NULL DEFAULT 0,
  change                 numeric(14, 2) NOT NULL DEFAULT 0,
  bill_promotion_ids     bigint[] NOT NULL DEFAULT '{}',
  item_count             integer NOT NULL DEFAULT 0,
  status                 text NOT NULL CHECK (status IN ('pending', 'paid', 'cancelled')),
  voided_at              timestamptz,
  void_reason            text NOT NULL DEFAULT '',
  voided_by              text,
  void_approved_by       text,
  tax_invoice_no         text,
  manual_discount_reason text NOT NULL DEFAULT '',
  manual_discount_by     text NOT NULL DEFAULT '',
  shift_id               bigint,
  void_shift_id          bigint,
  branch_id              bigint NOT NULL,
  terminal_id            integer,
  pos_id                 text NOT NULL DEFAULT '',
  vat_registered         boolean NOT NULL DEFAULT true,
  created_at             timestamptz NOT NULL,
  created_by             bigint,
  created_by_kind        text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at             timestamptz NOT NULL,
  updated_by             bigint,
  updated_by_kind        text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_sales_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_sales_tenant_no_key UNIQUE (tenant_id, order_no),
  CONSTRAINT dt_sales_branch_fkey FOREIGN KEY (tenant_id, branch_id) REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_sales_terminal_fkey FOREIGN KEY (tenant_id, terminal_id)
    REFERENCES dt_pos_terminals (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_sales_shift_fkey FOREIGN KEY (tenant_id, shift_id) REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_sales_void_shift_fkey FOREIGN KEY (tenant_id, void_shift_id)
    REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_sales_void_check CHECK ((voided_at IS NULL) OR status = 'cancelled')
);
CREATE INDEX dt_sales_branch_idx ON dt_sales (tenant_id, branch_id, sold_at);
CREATE INDEX dt_sales_terminal_idx ON dt_sales (tenant_id, terminal_id);
CREATE INDEX dt_sales_shift_idx ON dt_sales (tenant_id, shift_id);
CREATE INDEX dt_sales_void_shift_idx ON dt_sales (tenant_id, void_shift_id);

-- บรรทัดบิล (SaleLine) — อ้างด้วย line_index (saleLineIndex ของใบลดหนี้ / ใบเปลี่ยน) ลำดับคงที่; cogs = ต้นทุนทั้งบรรทัด (ไม่รวม VAT)
CREATE TABLE dt_sale_lines (
  tenant_id            bigint NOT NULL,
  sale_id              bigint NOT NULL,
  line_index           integer NOT NULL CHECK (line_index >= 0),
  product_id           bigint NOT NULL,
  sku                  text NOT NULL,
  name                 text NOT NULL,
  short_name           text NOT NULL,
  unit                 text NOT NULL,
  factor               integer NOT NULL CHECK (factor >= 1),
  qty                  integer NOT NULL CHECK (qty >= 1),
  unit_price           numeric(14, 2) NOT NULL,
  list_price           numeric(14, 2) NOT NULL,
  item_discount        numeric(14, 2) NOT NULL,
  bill_discount        numeric(14, 2) NOT NULL,
  manual_discount      numeric(14, 2) NOT NULL,
  amount               numeric(14, 2) NOT NULL,
  vat_type             text NOT NULL CHECK (vat_type IN ('vat7', 'exempt')),
  item_type            text NOT NULL CHECK (item_type IN ('stock', 'service')),
  vat                  numeric(14, 2) NOT NULL,
  promotion_ids        bigint[] NOT NULL DEFAULT '{}',
  free_of_promotion_id bigint,
  serial               text,
  warranty_months      integer NOT NULL DEFAULT 0,
  cogs                 numeric(14, 2) NOT NULL,
  created_at           timestamptz NOT NULL,
  created_by           bigint,
  created_by_kind      text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, sale_id, line_index),
  CONSTRAINT dt_sale_lines_sale_fkey FOREIGN KEY (tenant_id, sale_id) REFERENCES dt_sales (tenant_id, id) ON DELETE RESTRICT
);
-- SKU นี้มีประวัติการขาย (ลบ SKU ไม่ได้)
CREATE INDEX dt_sale_lines_product_idx ON dt_sale_lines (tenant_id, product_id);

-- การชำระ (SalePayment) — reference = เลขอนุมัติ / 4 หลักท้าย (เลขบัตรเต็ม → 400 ก่อนถึงนี่, PCI DSS)
CREATE TABLE dt_sale_payments (
  tenant_id          bigint NOT NULL,
  sale_id            bigint NOT NULL,
  position           integer NOT NULL CHECK (position >= 0),
  method_id          bigint NOT NULL,
  name               text NOT NULL,
  type               text NOT NULL,
  amount             numeric(14, 2) NOT NULL,
  tendered           numeric(14, 2) NOT NULL,
  reference          text NOT NULL DEFAULT '',
  installment_months integer,
  created_at         timestamptz NOT NULL,
  created_by         bigint,
  created_by_kind    text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, sale_id, position),
  CONSTRAINT dt_sale_payments_sale_fkey FOREIGN KEY (tenant_id, sale_id) REFERENCES dt_sales (tenant_id, id) ON DELETE RESTRICT
);
-- มีการขายที่ใช้ช่องทางนี้ (ลบช่องทางไม่ได้)
CREATE INDEX dt_sale_payments_method_idx ON dt_sale_payments (tenant_id, method_id);

-- ใบกำกับภาษีเต็มรูป: ผู้ซื้อเข้ารหัสทั้งก้อน (PiiCipher, AAD dt_tax_invoices.buyer:<tenant>) + hash ของเลขผู้เสียภาษี / passport สำหรับค้น;
-- ใช้ได้ 1 ใบต่อบิล (ยกเลิกแล้วออกใหม่ได้); ลงวันที่ / เลขตามวันขาย, branch_id = สาขาของบิล (E25)
CREATE TABLE dt_tax_invoices (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id           bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  invoice_no          text NOT NULL,
  sale_id             bigint NOT NULL,
  order_no            text NOT NULL,
  sale_date           timestamptz NOT NULL,
  date                timestamptz NOT NULL,
  issued_at           timestamptz NOT NULL,
  buyer_enc           bytea NOT NULL,
  buyer_tax_id_hash   bytea NOT NULL,
  issued_by           text NOT NULL,
  cancelled_at        timestamptz,
  cancel_reason       text NOT NULL DEFAULT '',
  replaces_invoice_no text,
  replaced_by_no      text,
  at_sale             boolean NOT NULL,
  branch_id           bigint NOT NULL,
  created_at          timestamptz NOT NULL,
  created_by          bigint,
  created_by_kind     text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at          timestamptz NOT NULL,
  updated_by          bigint,
  updated_by_kind     text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_tax_invoices_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_tax_invoices_tenant_no_key UNIQUE (tenant_id, invoice_no),
  CONSTRAINT dt_tax_invoices_sale_fkey FOREIGN KEY (tenant_id, sale_id) REFERENCES dt_sales (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_tax_invoices_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_tax_invoices_sale_idx ON dt_tax_invoices (tenant_id, sale_id);
CREATE INDEX dt_tax_invoices_branch_idx ON dt_tax_invoices (tenant_id, branch_id, date);
CREATE INDEX dt_tax_invoices_buyer_idx ON dt_tax_invoices (tenant_id, buyer_tax_id_hash);
CREATE UNIQUE INDEX dt_tax_invoices_valid_key ON dt_tax_invoices (tenant_id, sale_id) WHERE cancelled_at IS NULL;

