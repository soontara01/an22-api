-- V7 (ขั้น 8): กะขาย (Shift, docs/shift-plan.md) + ล็อกหน้าจอ POS (E48) + บิลที่พักไว้ (E48)
--   กะ = 1 เครื่อง (ลิ้นชัก) + 1 แคชเชียร์; เจ้าของกะ = cashier_user_id (ชื่อ cashier เป็น snapshot สำหรับแสดง / รายงาน)
--   method_id ของยอดนับ / ปรับปรุงไม่มี FK (ประวัติ — ชื่อช่องทางเป็น snapshot)
CREATE TABLE dt_shifts (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id             bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  shift_no              text NOT NULL,
  terminal_id           integer NOT NULL,
  branch_id             bigint NOT NULL,
  pos_id                text NOT NULL DEFAULT '',
  cashier_user_id       bigint NOT NULL,
  cashier               text NOT NULL,
  status                text NOT NULL CHECK (status IN ('open', 'closed')),
  opened_at             timestamptz NOT NULL DEFAULT now(),
  opening_float         numeric(14, 2) NOT NULL CHECK (opening_float >= 0),
  -- DenominationCount[] { value, qty }
  opening_denominations jsonb NOT NULL DEFAULT '[]',
  closed_at             timestamptz,
  closed_by             text,
  cash_denominations    jsonb NOT NULL DEFAULT '[]',
  deposit_amount        numeric(14, 2) NOT NULL DEFAULT 0 CHECK (deposit_amount >= 0),
  float_left            numeric(14, 2) NOT NULL DEFAULT 0,
  approval_status       text NOT NULL DEFAULT 'not_needed' CHECK (approval_status IN ('not_needed', 'pending', 'approved')),
  approved_by           text,
  approved_at           timestamptz,
  note                  text NOT NULL DEFAULT '',
  -- E48: หน้าจอ POS ของกะนี้ถูกล็อกตั้งแต่ (null = ไม่ล็อก)
  locked_at             timestamptz,
  created_at            timestamptz NOT NULL,
  created_by            bigint,
  created_by_kind       text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at            timestamptz NOT NULL,
  updated_by            bigint,
  updated_by_kind       text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_shifts_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_shifts_tenant_no_key UNIQUE (tenant_id, shift_no),
  CONSTRAINT dt_shifts_terminal_fkey FOREIGN KEY (tenant_id, terminal_id)
    REFERENCES dt_pos_terminals (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_shifts_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_shifts_closed_check CHECK ((status = 'closed') = (closed_at IS NOT NULL AND closed_by IS NOT NULL)),
  CONSTRAINT dt_shifts_lock_check CHECK (status = 'open' OR locked_at IS NULL)
);
CREATE INDEX dt_shifts_terminal_idx ON dt_shifts (tenant_id, terminal_id);
CREATE INDEX dt_shifts_branch_idx ON dt_shifts (tenant_id, branch_id, opened_at);
-- กะเปิดได้ 1 กะต่อเครื่อง และ 1 กะต่อคน (openShiftError — ตาข่ายเมื่อเปิดพร้อมกัน)
CREATE UNIQUE INDEX dt_shifts_open_terminal_key ON dt_shifts (tenant_id, terminal_id) WHERE status = 'open';
CREATE UNIQUE INDEX dt_shifts_open_cashier_key ON dt_shifts (tenant_id, cashier_user_id) WHERE status = 'open';

-- ยอดนับตอนปิดกะ (ShiftCount) ต่อช่องทาง — ลำดับตาม expectedByMethod()
CREATE TABLE dt_shift_counts (
  tenant_id       bigint NOT NULL,
  shift_id        bigint NOT NULL,
  position        integer NOT NULL CHECK (position >= 0),
  method_id       bigint NOT NULL,
  name            text NOT NULL,
  expected        numeric(14, 2) NOT NULL,
  counted         numeric(14, 2),
  close_check     text NOT NULL CHECK (close_check IN ('count', 'confirm', 'none')),
  confirmed_by    text,
  first_count     numeric(14, 2),
  reason_code     text CHECK (reason_code IN ('wrong_change', 'wrong_received', 'wrong_method', 'unknown', 'other')),
  reason          text NOT NULL DEFAULT '',
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, shift_id, position),
  CONSTRAINT dt_shift_counts_shift_fkey FOREIGN KEY (tenant_id, shift_id)
    REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT
);

-- เงินเข้า / ออกลิ้นชักระหว่างกะ (CashMovement) — at = created_at
CREATE TABLE dt_cash_movements (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  shift_id        bigint NOT NULL,
  type            text NOT NULL CHECK (type IN ('in', 'out')),
  amount          numeric(14, 2) NOT NULL CHECK (amount > 0),
  reason          text NOT NULL CHECK (btrim(reason) <> ''),
  by_name         text NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_cash_movements_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_cash_movements_shift_fkey FOREIGN KEY (tenant_id, shift_id)
    REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_cash_movements_shift_idx ON dt_cash_movements (tenant_id, shift_id);

-- เปิดลิ้นชักโดยไม่มีการขาย (DrawerOpen, S7) — at = created_at
CREATE TABLE dt_drawer_opens (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  shift_id        bigint NOT NULL,
  reason          text NOT NULL CHECK (btrim(reason) <> ''),
  by_name         text NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_drawer_opens_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_drawer_opens_shift_fkey FOREIGN KEY (tenant_id, shift_id)
    REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_drawer_opens_shift_idx ON dt_drawer_opens (tenant_id, shift_id);

-- ปรับปรุงยอดของกะที่ปิดแล้ว (ShiftAdjustment, S8) — ยอดนับเดิม / Z report ไม่เปลี่ยน; at = created_at
CREATE TABLE dt_shift_adjustments (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  shift_id        bigint NOT NULL,
  method_id       bigint NOT NULL,
  name            text NOT NULL,
  amount          numeric(14, 2) NOT NULL CHECK (amount <> 0),
  reason_code     text NOT NULL CHECK (reason_code IN ('count_error', 'found_cash', 'late_settlement', 'other')),
  reason          text NOT NULL DEFAULT '',
  by_name         text NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_shift_adjustments_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_shift_adjustments_shift_fkey FOREIGN KEY (tenant_id, shift_id)
    REFERENCES dt_shifts (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_shift_adjustments_shift_idx ON dt_shift_adjustments (tenant_id, shift_id);

-- บิลที่พักไว้ของ POS (HeldBill, E48) ต่อสาขา + เครื่อง — มีข้อมูลผู้ซื้อ จึงเข้ารหัสทั้งก้อน (PiiCipher, AAD dt_held_bills.payload:<tenant>);
-- terminal_id ไม่มี FK (ของชั่วคราว — ลบเมื่อเรียกคืน / ทิ้ง)
CREATE TABLE dt_held_bills (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  branch_id       bigint NOT NULL,
  terminal_id     integer NOT NULL,
  held_at         timestamptz NOT NULL,
  payload_enc     bytea NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_held_bills_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_held_bills_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_held_bills_branch_idx ON dt_held_bills (tenant_id, branch_id, terminal_id);

