ALTER TABLE dt_transfer_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON dt_transfer_lines
  USING (tenant_id = app_tenant_id()) WITH CHECK (tenant_id = app_tenant_id());

