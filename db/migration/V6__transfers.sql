-- V6 (ขั้น 6): ใบโอนสินค้าระหว่างสาขา (Transfer, E26–E29) — เลข TR-<สาขา>-YYYYMMDD-NNNN จาก dt_doc_counters
--   createdAt = created_at (stamp ของแถว), createdBy / receivedBy / cancelledBy = ชื่อผู้ทำ ณ ตอนนั้น (เอกสาร — เปลี่ยนชื่อผู้ใช้ทีหลังไม่กระทบ)
CREATE TABLE dt_transfers (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  transfer_no       text NOT NULL,
  from_branch_id    bigint NOT NULL,
  to_branch_id      bigint NOT NULL,
  status            text NOT NULL CHECK (status IN ('in_transit', 'received', 'cancelled')),
  note              text NOT NULL DEFAULT '',
  created_by_name   text NOT NULL,
  received_at       timestamptz,
  received_by_name  text,
  short_reason      text NOT NULL DEFAULT '',
  cancelled_at      timestamptz,
  cancelled_by_name text,
  cancel_reason     text NOT NULL DEFAULT '',
  created_at        timestamptz NOT NULL,
  created_by        bigint,
  created_by_kind   text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at        timestamptz NOT NULL,
  updated_by        bigint,
  updated_by_kind   text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_transfers_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_transfers_tenant_no_key UNIQUE (tenant_id, transfer_no),
  CONSTRAINT dt_transfers_from_branch_fkey FOREIGN KEY (tenant_id, from_branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_transfers_to_branch_fkey FOREIGN KEY (tenant_id, to_branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_transfers_branches_check CHECK (from_branch_id <> to_branch_id),
  CONSTRAINT dt_transfers_received_check CHECK ((status = 'received') = (received_at IS NOT NULL AND received_by_name IS NOT NULL)),
  CONSTRAINT dt_transfers_cancelled_check CHECK (
    (status = 'cancelled') = (cancelled_at IS NOT NULL AND cancelled_by_name IS NOT NULL AND btrim(cancel_reason) <> ''))
);
CREATE INDEX dt_transfers_from_branch_idx ON dt_transfers (tenant_id, from_branch_id);
CREATE INDEX dt_transfers_to_branch_idx ON dt_transfers (tenant_id, to_branch_id);

-- บรรทัดของใบโอน (TransferLine): sku / name / unit = ค่า ณ ตอนโอน; product_id ไม่มี FK (ประวัติ — ลบ SKU ที่รับ / ยกเลิกแล้วได้ ตาม E18
-- ใบที่ยังไม่รับกันลบในแอป); unit_cost = ทุนโอนต่อหน่วย (serial = เฉลี่ยทุนของเครื่อง), received_qty null = ยังไม่รับ
CREATE TABLE dt_transfer_lines (
  tenant_id        bigint NOT NULL,
  transfer_id      bigint NOT NULL,
  position         integer NOT NULL CHECK (position >= 0),
  product_id       bigint NOT NULL,
  sku              text NOT NULL,
  name             text NOT NULL,
  unit             text NOT NULL,
  qty              integer NOT NULL CHECK (qty > 0),
  serials          text[] NOT NULL DEFAULT '{}',
  unit_cost        numeric(14, 4) NOT NULL CHECK (unit_cost >= 0),
  received_qty     integer CHECK (received_qty BETWEEN 0 AND qty),
  received_serials text[] NOT NULL DEFAULT '{}',
  created_at       timestamptz NOT NULL,
  created_by       bigint,
  created_by_kind  text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at       timestamptz NOT NULL,
  updated_by       bigint,
  updated_by_kind  text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, transfer_id, position),
  CONSTRAINT dt_transfer_lines_product_key UNIQUE (tenant_id, transfer_id, product_id),
  CONSTRAINT dt_transfer_lines_transfer_fkey FOREIGN KEY (tenant_id, transfer_id)
    REFERENCES dt_transfers (tenant_id, id) ON DELETE RESTRICT
);
-- หาใบที่ยังไม่รับของ SKU (E18: ลบ / เปลี่ยนการคุม serial)
CREATE INDEX dt_transfer_lines_product_idx ON dt_transfer_lines (tenant_id, product_id);

CREATE TRIGGER set_row_stamp BEFORE INSERT OR UPDATE ON dt_transfers FOR EACH ROW EXECUTE FUNCTION set_row_stamp();
CREATE TRIGGER set_row_stamp BEFORE INSERT OR UPDATE ON dt_transfer_lines FOR EACH ROW EXECUTE FUNCTION set_row_stamp();

