-- บริษัทของ transaction ปัจจุบัน (set_config('app.tenant_id', …, true) จากแอป) — ไม่ตั้ง / ว่าง = null → RLS ไม่เห็นอะไร
CREATE FUNCTION app_tenant_id() RETURNS bigint
  LANGUAGE sql STABLE PARALLEL SAFE
  AS $$ SELECT nullif(current_setting('app.tenant_id', true), '')::bigint $$;

-- ตั้ง created_* / updated_* จาก now() + app.user_id / app.actor_kind — แอปลืมใส่ไม่ได้, UPDATE ทับ created_* ไม่ได้
--   actor_kind: user → *_by = dt_users.id · platform → dt_platform_admins.id · system (job, seed) → *_by = null
--   ตาราง append-only สร้าง trigger ด้วย argument 'append_only' (มีแค่ created_*, BEFORE INSERT)
--   system (seed / import) ใส่ created_at เองได้ — ผู้ใช้ / platform ได้ now() เสมอ
CREATE FUNCTION set_row_stamp() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
DECLARE
  kind text := coalesce(nullif(current_setting('app.actor_kind', true), ''), 'system');
  actor bigint := CASE WHEN kind = 'system' THEN NULL
                       ELSE nullif(current_setting('app.user_id', true), '')::bigint END;
  append_only boolean := TG_NARGS > 0 AND TG_ARGV[0] = 'append_only';
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.created_at := CASE WHEN kind = 'system' THEN coalesce(NEW.created_at, now()) ELSE now() END;
    NEW.created_by := actor;
    NEW.created_by_kind := kind;
    IF NOT append_only THEN
      NEW.updated_at := NEW.created_at;
      NEW.updated_by := actor;
      NEW.updated_by_kind := kind;
    END IF;
  ELSE
    NEW.created_at := OLD.created_at;
    NEW.created_by := OLD.created_by;
    NEW.created_by_kind := OLD.created_by_kind;
    NEW.updated_at := now();
    NEW.updated_by := actor;
    NEW.updated_by_kind := kind;
  END IF;
  RETURN NEW;
END
$$;

