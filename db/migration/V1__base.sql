  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_password_reset_tokens_token_hash_key UNIQUE (token_hash),
  CONSTRAINT dt_password_reset_tokens_user_fkey FOREIGN KEY (company_id, user_id)
