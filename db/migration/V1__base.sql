-- ข้อมูลบริษัท (CompanyInfo, E11) — 1 แถวต่อบริษัท; ค่าที่ CHECK ตรงกับ companyInfoError()
CREATE TABLE dt_company_info (
  tenant_id                   bigint PRIMARY KEY REFERENCES dt_companies (id) ON DELETE RESTRICT,
  name                        text NOT NULL,
  tax_id                      text NOT NULL DEFAULT '' CHECK (tax_id ~ '^([0-9]{13})?$'),
  vat_registered              boolean NOT NULL DEFAULT true,
  tax_invoice_paper           text NOT NULL DEFAULT 'A4' CHECK (tax_invoice_paper IN ('A4', '80mm')),
  exchange_days               integer NOT NULL DEFAULT 7 CHECK (exchange_days BETWEEN 0 AND 365),
  manual_discount_max_percent numeric(5, 2) NOT NULL DEFAULT 5 CHECK (manual_discount_max_percent BETWEEN 0 AND 100),
  require_shift               boolean NOT NULL DEFAULT true,
  shift_variance_limit        numeric(14, 2) NOT NULL DEFAULT 100 CHECK (shift_variance_limit BETWEEN 0 AND 100000),
  shift_max_hours             integer NOT NULL DEFAULT 12 CHECK (shift_max_hours BETWEEN 1 AND 48),
  staff_see_cost              boolean NOT NULL DEFAULT false,
  created_at                  timestamptz NOT NULL,
  created_by                  bigint,
  created_by_kind             text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at                  timestamptz NOT NULL,
  updated_by                  bigint,
  updated_by_kind             text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system'))
);

-- สาขา (Branch) — ไม่ลบ (active = false); ค่าที่ CHECK ตรงกับ branchError()
CREATE TABLE dt_branches (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  code            text NOT NULL CHECK (code ~ '^[A-Z0-9]{2,10}$'),
  name            text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
  branch_no       text NOT NULL CHECK (branch_no ~ '^[0-9]{5}$'),
  address         text NOT NULL,
  phone           text NOT NULL DEFAULT '',
  receipt_footer  text NOT NULL DEFAULT '' CHECK (char_length(receipt_footer) <= 200),
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_branches_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_branches_tenant_code_key UNIQUE (tenant_id, code),
  CONSTRAINT dt_branches_tenant_branch_no_key UNIQUE (tenant_id, branch_no)
);

-- ผู้ใช้ (User) — username เก็บตัวเล็ก (normalizeUsername), email '' = ไม่มี; created_at = User.createdAt
CREATE TABLE dt_users (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  username        text NOT NULL CHECK (username ~ '^[a-z0-9._-]{3,30}$'),
  name            text NOT NULL,
  email           text NOT NULL DEFAULT '',
  role            text NOT NULL CHECK (role IN ('owner', 'admin', 'user')),
  active          boolean NOT NULL DEFAULT true,
  all_branches    boolean NOT NULL DEFAULT false,
  password_hash   text NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_users_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_users_tenant_username_key UNIQUE (tenant_id, username),
  -- owner (E33): อีเมลบังคับ, ทุกสาขาเสมอ
  CONSTRAINT dt_users_owner_check CHECK (role <> 'owner' OR (all_branches AND email <> ''))
);
CREATE UNIQUE INDEX dt_users_tenant_email_key ON dt_users (tenant_id, lower(email)) WHERE email <> '';
-- owner 1 คนต่อบริษัท
CREATE UNIQUE INDEX dt_users_tenant_owner_key ON dt_users (tenant_id) WHERE role = 'owner';

-- สาขาที่ผู้ใช้เข้าได้ (User.branchIds) — ว่างเมื่อ all_branches (E9)
CREATE TABLE dt_user_branches (
  tenant_id       bigint NOT NULL,
  user_id         bigint NOT NULL,
  branch_id       bigint NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, user_id, branch_id),
  CONSTRAINT dt_user_branches_user_fkey FOREIGN KEY (tenant_id, user_id)
    REFERENCES dt_users (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_user_branches_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_user_branches_branch_idx ON dt_user_branches (tenant_id, branch_id);

-- เมนูที่ role user เห็น (MenuAccess) — 1 แถวต่อบริษัท
CREATE TABLE dt_menu_access (
  tenant_id       bigint PRIMARY KEY REFERENCES dt_companies (id) ON DELETE RESTRICT,
  user_menus      text[] NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system'))
