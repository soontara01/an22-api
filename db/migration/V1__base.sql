-- tenant (Company + การเก็บเงิน E35 + คำขอลบ E39) — code ห้ามใช้ซ้ำแม้ลบแล้ว
CREATE TABLE dt_companies (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                  text NOT NULL CHECK (code ~ '^[A-Z0-9]+$'),
  active                boolean NOT NULL DEFAULT true,
  plan_id               text NOT NULL CHECK (plan_id IN ('starter', 'standard', 'pro')),
  suspended_reason      text CHECK (suspended_reason IN ('overdue', 'platform', 'deletion')),
  suspend_note          text,
  trial_ends_on         date,
  next_invoice_on       date NOT NULL,
  deletion_requested_at timestamptz,
  deletion_requested_by text,
  deletion_reason       text,
  purge_after           date,
  deleted_at            timestamptz,
  deleted_name          text,
  created_at            timestamptz NOT NULL,
  created_by            bigint,
  created_by_kind       text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at            timestamptz NOT NULL,
  updated_by            bigint,
  updated_by_kind       text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_companies_code_key UNIQUE (code)
);

-- ผู้ดูแลแพลตฟอร์ม (E36) — ไม่ใช่ผู้ใช้ของบริษัทใด
CREATE TABLE dt_platform_admins (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username        text NOT NULL CHECK (username ~ '^[a-z0-9._-]{3,30}$'),
  name            text NOT NULL,
  password_hash   text NOT NULL,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_platform_admins_username_key UNIQUE (username)
);

-- ใบแจ้งหนี้ค่าบริการ SaaS (E35) — ไม่ใช่เอกสารภาษีของร้าน; 1 ใบต่อบริษัทต่อรอบ (job รันซ้ำได้ผลเดิม)
CREATE TABLE dt_billing_invoices (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  invoice_no      text NOT NULL CHECK (invoice_no ~ '^SUB-[0-9]{6}-[0-9]{4,}$'),
  plan_id         text NOT NULL CHECK (plan_id IN ('starter', 'standard', 'pro')),
  period_start    date NOT NULL,
  period_end      date NOT NULL CHECK (period_end >= period_start),
  amount          numeric(14, 2) NOT NULL CHECK (amount >= 0),
  issued_on       date NOT NULL,
  due_date        date NOT NULL,
  status          text NOT NULL CHECK (status IN ('open', 'paid', 'void')),
  paid_at         timestamptz,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_billing_invoices_invoice_no_key UNIQUE (invoice_no),
  CONSTRAINT dt_billing_invoices_company_period_key UNIQUE (company_id, period_start),
  CONSTRAINT dt_billing_invoices_paid_check CHECK ((status = 'paid') = (paid_at IS NOT NULL))
);

-- ตัวนับเลขเอกสารระดับแพลตฟอร์ม (SUB-YYYYMM-NNNN) — แบบเดียวกับ dt_doc_counters
