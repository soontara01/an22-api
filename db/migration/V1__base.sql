-- audit log (AuditEvent, E40) — append-only: an22_app ได้แค่ INSERT + SELECT; AuditEvent.at = created_at
--   user_id / ref ไม่มี FK (ประวัติต้องอยู่แม้ record ถูกลบ); terminal_id ไม่มี FK (เครื่องลบได้)
CREATE TABLE dt_audit_log (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  actor_kind      text NOT NULL CHECK (actor_kind IN ('user', 'platform', 'system')),
  user_id         bigint,
  user_name       text NOT NULL,
  branch_id       bigint,
  terminal_id     bigint,
  action          text NOT NULL CHECK (action IN (
                    'login', 'login_failed', 'sale_void', 'manual_discount', 'credit_note', 'tax_invoice_reissue',
                    'stock_out', 'serial_remove', 'transfer_cancel', 'price_change', 'promotion_change',
                    'user_change', 'user_password', 'owner_transfer', 'plan_change', 'signup', 'company_suspend',
                    'company_reactivate', 'invoice_paid', 'company_export', 'deletion_request', 'deletion_cancel',
                    'password_reset', 'menu_access', 'company_settings', 'branch_settings', 'branch_change',
                    'terminal_change', 'shift_close_other', 'shift_approve', 'shift_adjust')),
  ref_kind        text CHECK (ref_kind IN (
                    'sale', 'credit_note', 'tax_invoice', 'product', 'transfer', 'price', 'promotion', 'user',
                    'branch', 'terminal', 'shift', 'company')),
  ref_id          bigint,
  ref_label       text,
  detail          text NOT NULL DEFAULT '',
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_audit_log_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_audit_log_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_audit_log_ref_check CHECK ((ref_kind IS NULL) = (ref_label IS NULL) AND (ref_kind IS NOT NULL OR ref_id IS NULL))
);
CREATE INDEX dt_audit_log_tenant_at_idx ON dt_audit_log (tenant_id, created_at);
CREATE INDEX dt_audit_log_branch_idx ON dt_audit_log (tenant_id, branch_id);

-- ตัวนับเลขเอกสาร (db/DocNumbers): INSERT … ON CONFLICT DO UPDATE SET last_no = last_no + 1 RETURNING ใน transaction ของเอกสาร
CREATE TABLE dt_doc_counters (
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  prefix          text NOT NULL,
  last_no         integer NOT NULL CHECK (last_no >= 0),
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, prefix)
);

-- ตารางของ platform ที่อ้างผู้ใช้ของบริษัท — สร้างหลัง dt_users
