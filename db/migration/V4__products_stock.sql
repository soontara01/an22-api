-- V4 (ขั้น 5): SKU + สต็อกต่อสาขา + บัตรสต็อก + serial
--   ทุนเฉลี่ย numeric(14,4) = movingAverage() ปัด round4 (ตกลง 2026-10-22); ทุนต่อหน่วย (มาตรฐาน / ผู้จำหน่าย / serial) numeric(14,4)
--   เงิน / มูลค่า numeric(14,2); จำนวนเป็นหน่วยฐาน integer
--   ประวัติ (stock_movements, serial_numbers) ไม่มี FK ไป products — ลบ SKU ที่หมดสต็อกแล้วได้ (ตาม mock) แต่ประวัติอยู่ต่อ

-- SKU (Product) — stock / avgCost / minStock / maxStock อยู่ใน dt_branch_stock (D1); currentPrice / categoryPath คำนวณตอนอ่าน
CREATE TABLE dt_products (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  sku             text NOT NULL CHECK (btrim(sku) <> ''),
  name            text NOT NULL,
  short_name      text NOT NULL DEFAULT '' CHECK (char_length(short_name) <= 20),
  category_id     bigint,
  unit            text NOT NULL DEFAULT 'ชิ้น',
  barcode         text NOT NULL DEFAULT '',
  brand           text NOT NULL DEFAULT '',
  model           text NOT NULL DEFAULT '',
  item_type       text NOT NULL DEFAULT 'stock' CHECK (item_type IN ('stock', 'service')),
  image_url       text NOT NULL DEFAULT '',
  vat_type        text NOT NULL DEFAULT 'vat7' CHECK (vat_type IN ('vat7', 'exempt')),
  cost            numeric(14, 4) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  warranty_months integer NOT NULL DEFAULT 0 CHECK (warranty_months >= 0),
  serial_control  boolean NOT NULL DEFAULT false,
  serial_prefix   text NOT NULL DEFAULT '',
  serial_length   integer CHECK (serial_length > 0),
  sale_status     text NOT NULL DEFAULT 'active' CHECK (sale_status IN ('active', 'no_sale', 'no_purchase', 'discontinued')),
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_products_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_products_category_fkey FOREIGN KEY (tenant_id, category_id)
    REFERENCES dt_categories (tenant_id, id) ON DELETE RESTRICT,
  -- สินค้าบริการไม่มี serial (withServiceRules)
  CONSTRAINT dt_products_service_check CHECK (item_type = 'stock' OR NOT serial_control)
);
-- รหัส SKU ไม่ซ้ำในบริษัท ไม่สนตัวพิมพ์
CREATE UNIQUE INDEX dt_products_tenant_sku_key ON dt_products (tenant_id, upper(sku));
CREATE INDEX dt_products_category_idx ON dt_products (tenant_id, category_id);

-- หน่วยแพ็ก (PackUnit) — ลำดับตามที่ส่งมา (position); serial SKU ไม่มี
CREATE TABLE dt_product_pack_units (
  tenant_id       bigint NOT NULL,
  product_id      bigint NOT NULL,
  position        integer NOT NULL,
  unit            text NOT NULL CHECK (btrim(unit) <> ''),
  factor          integer NOT NULL CHECK (factor > 1),
  barcode         text NOT NULL DEFAULT '',
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, product_id, position),
  CONSTRAINT dt_product_pack_units_unit_key UNIQUE (tenant_id, product_id, unit),
  CONSTRAINT dt_product_pack_units_product_fkey FOREIGN KEY (tenant_id, product_id)
    REFERENCES dt_products (tenant_id, id) ON DELETE RESTRICT
);

-- ผู้จำหน่ายของ SKU (SkuSupplier) — หลัก 1 รายต่อ SKU
CREATE TABLE dt_product_suppliers (
  tenant_id       bigint NOT NULL,
  product_id      bigint NOT NULL,
  supplier_id     bigint NOT NULL,
  position        integer NOT NULL,
  supplier_sku    text NOT NULL DEFAULT '',
  cost            numeric(14, 4) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  lead_time_days  integer NOT NULL DEFAULT 0 CHECK (lead_time_days >= 0),
  moq             integer NOT NULL DEFAULT 0 CHECK (moq >= 0),
  is_main         boolean NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, product_id, supplier_id),
  CONSTRAINT dt_product_suppliers_product_fkey FOREIGN KEY (tenant_id, product_id)
    REFERENCES dt_products (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_product_suppliers_supplier_fkey FOREIGN KEY (tenant_id, supplier_id)
    REFERENCES dt_suppliers (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_product_suppliers_supplier_idx ON dt_product_suppliers (tenant_id, supplier_id);
CREATE UNIQUE INDEX dt_product_suppliers_main_key ON dt_product_suppliers (tenant_id, product_id) WHERE is_main;

-- สต็อกต่อสาขา (BranchStock, D1) — ไม่มีแถว = 0 ทั้งหมด (E13); serial SKU: stock / avg_cost = นับ / เฉลี่ย serial in_stock ของสาขา
CREATE TABLE dt_branch_stock (
  tenant_id       bigint NOT NULL,
  branch_id       bigint NOT NULL,
  product_id      bigint NOT NULL,
  stock           integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  avg_cost        numeric(14, 4) NOT NULL DEFAULT 0 CHECK (avg_cost >= 0),
  min_stock       integer NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  max_stock       integer NOT NULL DEFAULT 0 CHECK (max_stock >= 0),
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, branch_id, product_id),
  CONSTRAINT dt_branch_stock_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_branch_stock_product_fkey FOREIGN KEY (tenant_id, product_id)
    REFERENCES dt_products (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_branch_stock_product_idx ON dt_branch_stock (tenant_id, product_id);

-- บัตรสต็อก (StockMovement) — append-only; StockMovement.date = created_at; ยอดคงเหลือหลังรายการของ (สาขา, SKU)
CREATE TABLE dt_stock_movements (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  branch_id        bigint NOT NULL,
  product_id       bigint NOT NULL,
  type             text NOT NULL CHECK (type IN ('opening', 'receive', 'issue', 'transfer_out', 'transfer_in')),
  qty              integer NOT NULL,
  unit_cost        numeric(14, 2) NOT NULL,
  total_cost       numeric(14, 2) NOT NULL,
  balance_qty      integer NOT NULL,
  balance_avg_cost numeric(14, 4) NOT NULL,
  balance_value    numeric(14, 2) NOT NULL,
  serials          text[] NOT NULL DEFAULT '{}',
  note             text NOT NULL DEFAULT '',
  created_at       timestamptz NOT NULL,
  created_by       bigint,
  created_by_kind  text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_stock_movements_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_stock_movements_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_stock_movements_card_idx ON dt_stock_movements (tenant_id, branch_id, product_id, created_at, id);
CREATE INDEX dt_stock_movements_product_idx ON dt_stock_movements (tenant_id, product_id);

-- Serial (SerialNumber) — 1 serial = 1 แถวทั้งบริษัท, ไม่ลบ (เปลี่ยน status); รับคืนใช้แถวเดิม (B18)
CREATE TABLE dt_serial_numbers (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  product_id      bigint NOT NULL,
  branch_id       bigint NOT NULL,
  serial          text NOT NULL CHECK (serial ~ '^[A-Z0-9-]+$'),
  status          text NOT NULL CHECK (status IN ('in_stock', 'in_transit', 'sold', 'damaged', 'other')),
  received_at     timestamptz NOT NULL,
  removed_at      timestamptz,
  note            text NOT NULL DEFAULT '',
  cost            numeric(14, 4) NOT NULL CHECK (cost >= 0),
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_serial_numbers_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_serial_numbers_tenant_serial_key UNIQUE (tenant_id, serial),
  CONSTRAINT dt_serial_numbers_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_serial_numbers_branch_idx ON dt_serial_numbers (tenant_id, branch_id);
CREATE INDEX dt_serial_numbers_product_idx ON dt_serial_numbers (tenant_id, product_id, branch_id, status);

