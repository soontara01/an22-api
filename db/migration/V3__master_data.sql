-- V3 (ขั้น 4): ข้อมูลหลักที่ไม่ขึ้นกับ SKU — หมวดหมู่, ผู้จำหน่าย, ช่องทางชำระเงิน, เครื่อง POS
-- กติกาเดียวกับ V1: dt_ + tenant_id + RLS, FK รวม tenant RESTRICT + index, created_* / updated_* ด้วย trigger, grant

-- หมวดหมู่ (Category) 3 ระดับ: แผนก > หมวด > หมวดย่อย — productCount คำนวณตอนอ่าน (ขั้น 5)
CREATE TABLE dt_categories (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  code            text NOT NULL CHECK (code ~ '^[A-Z0-9-]+$'),
  name            text NOT NULL CHECK (btrim(name) <> ''),
  parent_id       bigint,
  level           smallint NOT NULL CHECK (level BETWEEN 1 AND 3),
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_categories_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_categories_tenant_code_key UNIQUE (tenant_id, code),
  CONSTRAINT dt_categories_parent_fkey FOREIGN KEY (tenant_id, parent_id)
    REFERENCES dt_categories (tenant_id, id) ON DELETE RESTRICT,
  CONSTRAINT dt_categories_root_check CHECK ((parent_id IS NULL) = (level = 1))
);
CREATE INDEX dt_categories_parent_idx ON dt_categories (tenant_id, parent_id);

-- ผู้จำหน่าย (Supplier) — productCount คำนวณตอนอ่าน (ขั้น 5)
CREATE TABLE dt_suppliers (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  code              text NOT NULL CHECK (code ~ '^[A-Z0-9-]+$'),
  name              text NOT NULL CHECK (btrim(name) <> ''),
  tax_id            text NOT NULL CHECK (tax_id ~ '^[0-9]{13}$'),
  branch_type       text NOT NULL CHECK (branch_type IN ('head', 'branch')),
  branch_no         text NOT NULL DEFAULT '',
  address           text NOT NULL DEFAULT '',
  contact_name      text NOT NULL DEFAULT '',
  phone             text NOT NULL DEFAULT '',
  email             text NOT NULL DEFAULT '',
  credit_days       integer NOT NULL DEFAULT 30 CHECK (credit_days >= 0),
  bank_name         text NOT NULL DEFAULT '',
  bank_account_no   text NOT NULL DEFAULT '',
  bank_account_name text NOT NULL DEFAULT '',
  note              text NOT NULL DEFAULT '',
  active            boolean NOT NULL DEFAULT true,
  created_at        timestamptz NOT NULL,
  created_by        bigint,
  created_by_kind   text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at        timestamptz NOT NULL,
  updated_by        bigint,
  updated_by_kind   text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_suppliers_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_suppliers_tenant_code_key UNIQUE (tenant_id, code),
  CONSTRAINT dt_suppliers_tenant_tax_branch_key UNIQUE (tenant_id, tax_id, branch_type, branch_no),
  CONSTRAINT dt_suppliers_branch_no_check CHECK (
    (branch_type = 'head' AND branch_no = '') OR (branch_type = 'branch' AND branch_no ~ '^[0-9]{5}$'))
);

-- ช่องทางชำระเงิน (PaymentMethod) — ปุ่มของ POS เรียงตาม sort_order
CREATE TABLE dt_payment_methods (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  code               text NOT NULL CHECK (code ~ '^[A-Z0-9-]{1,20}$'),
  name               text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 20),
  type               text NOT NULL CHECK (type IN ('cash', 'card', 'qr', 'transfer', 'e_wallet', 'installment', 'other')),
  active             boolean NOT NULL DEFAULT true,
  sort_order         integer NOT NULL,
  require_reference  boolean NOT NULL DEFAULT false,
  reference_label    text NOT NULL DEFAULT '',
  min_amount         numeric(14, 2) NOT NULL DEFAULT 0 CHECK (min_amount >= 0),
  max_amount         numeric(14, 2) CHECK (max_amount > 0 AND max_amount >= min_amount),
  fee_percent        numeric(5, 2) NOT NULL DEFAULT 0 CHECK (fee_percent BETWEEN 0 AND 10),
  cash_rounding      text NOT NULL DEFAULT 'none' CHECK (cash_rounding IN ('none', '0.25', '1')),
  prompt_pay_id      text NOT NULL DEFAULT '',
  bank_account       text NOT NULL DEFAULT '',
  installment_months integer[] NOT NULL DEFAULT '{}',
  close_check        text NOT NULL CHECK (close_check IN ('count', 'confirm', 'none')),
  note               text NOT NULL DEFAULT '',
  created_at         timestamptz NOT NULL,
  created_by         bigint,
  created_by_kind    text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at         timestamptz NOT NULL,
  updated_by         bigint,
  updated_by_kind    text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  CONSTRAINT dt_payment_methods_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT dt_payment_methods_tenant_code_key UNIQUE (tenant_id, code)
);

-- เครื่อง POS (PosTerminal, T1 / T5 / E8): id = เลขเครื่องที่ผู้ใช้กำหนด ไม่ซ้ำในบริษัท, เปลี่ยนไม่ได้
CREATE TABLE dt_pos_terminals (
  tenant_id       bigint NOT NULL REFERENCES dt_companies (id) ON DELETE RESTRICT,
  id              integer NOT NULL CHECK (id BETWEEN 1 AND 999),
  name            text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 40),
  pos_id          text NOT NULL DEFAULT '' CHECK (char_length(pos_id) <= 30),
  branch_id       bigint NOT NULL,
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL,
  created_by      bigint,
  created_by_kind text NOT NULL CHECK (created_by_kind IN ('user', 'platform', 'system')),
  updated_at      timestamptz NOT NULL,
  updated_by      bigint,
  updated_by_kind text NOT NULL CHECK (updated_by_kind IN ('user', 'platform', 'system')),
  PRIMARY KEY (tenant_id, id),
  CONSTRAINT dt_pos_terminals_branch_fkey FOREIGN KEY (tenant_id, branch_id)
    REFERENCES dt_branches (tenant_id, id) ON DELETE RESTRICT
);
CREATE INDEX dt_pos_terminals_branch_idx ON dt_pos_terminals (tenant_id, branch_id);
-- POS ID ของกรมสรรพากรไม่ซ้ำในบริษัทเมื่อมี
CREATE UNIQUE INDEX dt_pos_terminals_tenant_pos_id_key ON dt_pos_terminals (tenant_id, pos_id) WHERE pos_id <> '';

